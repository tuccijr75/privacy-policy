'use strict';
const assert=require('node:assert/strict');
const oc=require('./MM_OC.user.js');
const raw=(id,status='Successful',cpr=80)=>({id,name:'Test Job',difficulty:3,status,created_at:100,executed_at:status==='Recruiting'?null:200,slots:[{position:'Driver',position_info:{id:'driver',label:'Driver'},user:{id:77,joined_at:90,progress:0},checkpoint_pass_rate:cpr,item_requirement:null}]});
const c=oc.normalizeCrime(raw(1));
assert.equal(c.id,1);assert.equal(c.slots[0].memberId,77);
assert.equal(oc.normalizeCrime(raw(2,'Recruiting')).executedAt,null);
assert.equal(oc.normalizeCrime(raw(3,'Recruiting',0)).slots[0].cpr,0);
assert.equal(oc.normalizeCrime({...raw(4),status:'invalid'}),null);
assert.throws(()=>oc.normalizeCrimes({crimes:[{id:1}]}));
const e=oc.evidence([c],77,'Test Job','Driver');
assert.equal(e.attempts,1);assert.equal(e.wins,1);assert.equal(e.avgCpr,80);
assert.equal(oc.evidence([c],99,'Test Job','Driver').attempts,0);
const slot1={slotId:'a',role:'Driver'},slot2={slotId:'b',role:'Driver'};
const match=oc.optimizeAssignment([{slot:slot1,candidates:[{id:1,s:{value:.9,confidence:1}},{id:2,s:{value:.8,confidence:1}}]},{slot:slot2,candidates:[{id:1,s:{value:.89,confidence:1}},{id:2,s:{value:.1,confidence:1}}]}]);
assert.deepEqual(match.map(m=>m.member.id),[2,1]);
assert.deepEqual(oc.optimizeAssignment([]),[]);
assert.equal(oc.optimizeAssignment([{slot:slot1,candidates:[]}]).length,0);
assert.equal(oc.nextCrimeOffset({_metadata:{links:{next:null}}},0),null);
assert.equal(oc.nextCrimeOffset({_metadata:{links:{next:'https://api.torn.com/v2/faction/crimes?offset=100'}}},0),100);
assert.throws(()=>oc.nextCrimeOffset({_metadata:{links:{next:'https://invalid.example/v2/faction/crimes?offset=100'}}},0));
assert.throws(()=>oc.nextCrimeOffset({_metadata:{links:{next:'https://api.torn.com/v2/faction/crimes?offset=0'}}},0));
const p=oc.recommendations({name:'Test Job',slots:[{slotId:'b',role:'Unknown',memberId:null}]},[{id:77,name:'Tester',isInOc:false}],[c]);
assert.equal(p.selected.length,0);
assert.ok(oc.score(e).confidence>0&&oc.score(e).confidence<1);
